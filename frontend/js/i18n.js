export const LANGUAGES = [
  { code: 'pt-BR', label: 'Português' },
  { code: 'en', label: 'English' },
  { code: 'es', label: 'Español' }
]

export function idiomaAtual() {
  const salvo = localStorage.getItem('hestia.language')
  if (salvo && LOCALES[salvo]) return salvo
  const navegador = (navigator.languages || [navigator.language]).find((codigo) => {
    if (codigo && LOCALES[codigo]) return true
    if (codigo && LOCALES[codigo.slice(0, 2)]) return true
  })
  if (!navegador) return 'pt-BR'
  if (LOCALES[navegador]) return navegador
  return LOCALES[navegador.slice(0, 2)] ? navegador.slice(0, 2) : 'pt-BR'
}

export function t(chave) {
  const idioma = idiomaAtual()
  return LOCALES[idioma]?.[chave] || LOCALES['pt-BR'][chave] || chave
}

export function localeId() {
  return idiomaAtual() === 'pt-BR' ? 'pt-BR' : idiomaAtual()
}

export function aplicarIdioma(idioma) {
  if (!LOCALES[idioma]) idioma = 'pt-BR'
  localStorage.setItem('hestia.language', idioma)
  document.documentElement.lang = idioma
  document.querySelectorAll('[data-i18n]').forEach((elemento) => {
    elemento.textContent = t(elemento.dataset.i18n)
  })
  document.querySelectorAll('[data-i18n-placeholder]').forEach((elemento) => {
    elemento.placeholder = t(elemento.dataset.i18nPlaceholder)
  })
  document.querySelectorAll('[data-i18n-aria]').forEach((elemento) => {
    elemento.setAttribute('aria-label', t(elemento.dataset.i18nAria))
  })
  document.querySelectorAll('[data-i18n-title]').forEach((elemento) => {
    elemento.title = t(elemento.dataset.i18nTitle)
  })
  const seletor = document.getElementById('seletorIdioma')
  if (seletor) {
    seletor.querySelectorAll('[data-idioma]').forEach((botao) => {
      const ativo = botao.dataset.idioma === idioma
      botao.classList.toggle('ativo', ativo)
      botao.setAttribute('aria-checked', String(ativo))
      botao.tabIndex = ativo ? 0 : -1
    })
  }
  document.dispatchEvent(new CustomEvent('hestia:idioma', { detail: { idioma } }))
}

